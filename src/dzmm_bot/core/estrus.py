_SLOT_ORDER = (
    "opening", "act", "interaction", "detail", "reaction", "afterglow", "peak",
)


class _SafeDict(dict):
    """缺键返回空串：模板里没被填到的占位符不会炸掉整段文案。"""

    def __missing__(self, key):  # noqa: D105
        return ""


def _fill(template: str, values: Mapping[str, str]) -> str:
    return template.format_map(_SafeDict(values))


def fallback_climax_text(
    name: str,
    gender: str,
    rng,
    chopper_name: str | None = None,
) -> str:
    """按性别组装一段兜底高潮长文（必有输出，不依赖 AI）。"""
    key = gender if gender in _FALLBACKS else "unknown"
    bank = _FALLBACKS[key]
    chopper = (chopper_name or "").strip()
    slots: list[str] = []
    for slot in _SLOT_ORDER:
        if slot == "interaction":
            if not chopper:
                continue
            slots.append(rng.choice(bank["interaction"]))
            continue
        if slot == "detail":
            slots.append(rng.choice(_SHARED_FALLBACKS["detail"]))
            continue
        slots.append(rng.choice(bank[slot]))
    slots.append(
        rng.choice(bank["closing_with"] if chopper else bank["closing_solo"])
    )
    values = {"name": name, "chopper": chopper}
    return "".join(_fill(template, values) for template in slots)


