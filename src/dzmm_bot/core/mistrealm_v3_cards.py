def validate_deck(faction, leader, counts):
    if faction not in FACTIONS: raise ValueError('未知阵营')
    if leader not in CARDS or CARDS[leader]['type'] != 'leader' or CARDS[leader]['faction'] != faction:
        raise ValueError('领袖必须属于当前阵营')
    if not isinstance(counts, dict): raise ValueError('牌组必须是卡牌数量表')
    normalized = {}
    for cid, count in counts.items():
        if cid not in CARDS: raise ValueError('未知卡牌')
        c = CARDS[cid]
        if type(count) is not int or not 0 <= count <= c['copies']: raise ValueError('卡牌超出携带上限')
        if c['type'] == 'leader' or c['faction'] not in (faction, 'neutral'): raise ValueError('牌组含有其他阵营或领袖')
        if count: normalized[cid] = count
    units = sum(n for cid, n in normalized.items() if CARDS[cid]['type'] == 'unit')
    heroes = sum(n for cid, n in normalized.items() if CARDS[cid]['hero'])
    if sum(normalized.values()) != 20: raise ValueError('第三版牌组必须恰好20张')
    if units < 14: raise ValueError('至少需要14张单位，术卡最多6张')
    if heroes > 2: raise ValueError('最多携带2张英雄')
    return dict(faction=faction, leader=leader, counts=dict(sorted(normalized.items())), rules_version=3)
